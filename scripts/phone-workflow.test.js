import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {pathToFileURL} from 'node:url';
import {phoneWorkflowSchema,registerPhoneWorkflow,checkPhoneImei,phoneWorkflowError,getPhoneSaveRetry,phoneRequestFingerprint} from '../phone-workflow.js';

test('phone workflow integrates duplicate protection, retry-safe imports, bulk moves, prices, tracking, and history', {skip:!process.env.PGLITE_TEST_MODULE}, async t=>{
  const {PGlite}=await import(pathToFileURL(process.env.PGLITE_TEST_MODULE).href);
  const db=new PGlite();t.after(()=>db.close());
  const source=fs.readFileSync(new URL('../server.js',import.meta.url),'utf8');
  await db.exec(source.slice(source.indexOf('create table if not exists phone_invoices ('),source.indexOf('create table if not exists phone_manual_returns (')));
  await db.exec(source.slice(source.indexOf('create table if not exists phone_holding_purchases ('),source.indexOf('create table if not exists phone_online_orders (')));
  await db.exec("alter table phone_invoices add column archived_at timestamptz; alter table phone_holding_purchases add column holding_type text not null default 'Holding For Sale'; create table app_migrations(migration_key text primary key);");
  await db.exec("insert into phone_invoices(buyer,label,archived_at) values('KT','First fresh start','2026-10-09T18:00:00Z');");
  await db.exec(phoneWorkflowSchema);
  const routes=new Map();
  const app=Object.fromEntries(['get','post','patch'].map(method=>[method,(path,...handlers)=>routes.set(`${method} ${path}`,handlers)]));
  const pool={query:(...args)=>db.query(...args),connect:async()=>({query:(...args)=>db.query(...args),release(){}})};
  const auth=(req,res,next)=>req.authorized?next():res.status(401).json({error:'Sign in.'});
  const helpers={getKtPrices:async()=>[],getAtlasPrices:async()=>[],findPhonePrice:()=>0,nextPhoneInvoiceItemStart:async(client,id)=>Number((await client.query('select coalesce(max(invoice_item_start+quantity),1) as start from phone_purchases where invoice_id=$1',[id])).rows[0].start)};
  registerPhoneWorkflow(app,pool,auth,helpers);
  const sandbox={app,pool,requirePhoneAuth:auth,...helpers,checkPhoneImei,phoneWorkflowError,getPhoneSaveRetry,phoneRequestFingerprint,console:{error(){}},Date,
    normalizeBuyer:v=>['KT','Atlas'].includes(v)?v:'',normalizeDeviceType:v=>v || 'Phone',normalizeConditionType:v=>v || 'Used',normalizeHoldingType:v=>v || 'Holding For Sale',
    isAllowedPhotoDataUrl:()=>false,localDateInTimeZone:()=>'2026-10-17',
    findPhoneInvoice:async(client,id,buyer)=>(await client.query("select * from phone_invoices where id=$1 and buyer=$2 and status='Pending' and archived_at is null",[id,buyer])).rows[0]};
  vm.createContext(sandbox);
  vm.runInContext(source.slice(source.indexOf('app.post("/api/phone-purchases",'),source.indexOf('app.post("/api/phone-purchases/move-latest",')),sandbox);
  vm.runInContext(source.slice(source.indexOf('app.post("/api/phone-holding",'),source.indexOf('app.post("/api/phone-manual-returns",')),sandbox);
  vm.runInContext(source.slice(source.indexOf('app.patch("/api/phone-invoices/:id/status",'),source.indexOf('app.post("/api/phone-purchases",')),sandbox);
  async function call(method,path,{body={},id,query={},authorized=true}={}){
    const handlers=routes.get(`${method} ${path}`);assert.ok(handlers,path);
    const req={body,params:{id},query,authorized};
    const res={statusCode:200,status(n){this.statusCode=n;return this;},json(value){this.body=JSON.parse(JSON.stringify(value));return this;}};
    let allowed=false;await handlers[0](req,res,()=>{allowed=true;});if(allowed)await handlers[1](req,res);
    return res;
  }
  const invoice=async(label,buyer='KT')=>(await db.query('insert into phone_invoices(buyer,label) values($1,$2) returning *',[buyer,label])).rows[0];
  const sourceInvoice=await invoice('Source'),target=await invoice('Destination');
  assert.equal((await call('get','/api/phone-dashboard-settings')).body.start_date,'2026-10-09','Fresh-start date comes from the original KT archive');
  assert.equal((await call('patch','/api/phone-dashboard-settings',{body:{start_date:'2026-02-30'}})).statusCode,400);
  assert.equal((await call('patch','/api/phone-dashboard-settings',{body:{start_date:'2026-10-10'}})).body.start_date,'2026-10-10');
  const body={buyer:'KT',invoice_id:sourceInvoice.id,model:'iPhone 18 Pro 256GB',quantity:1,cost_each:800,imei:'123-456-789',placed_at:'Mike',client_request_id:'test-save-reference-0001'};
  for (const key of routes.keys()) {
    const [method,path]=key.split(' ');
    assert.equal((await call(method,path,{id:sourceInvoice.id,authorized:false})).statusCode,401,`${path} requires authentication`);
  }
  const saved=await call('post','/api/phone-purchases',{body});
  assert.equal(saved.statusCode,200);
  const purchaseId=saved.body.purchase.id;
  const retry=await call('post','/api/phone-purchases',{body});
  assert.equal(retry.body.purchase.id,purchaseId);
  assert.equal(retry.body.reused,true);
  assert.equal((await call('post','/api/phone-purchases',{body:{...body,cost_each:10}})).statusCode,409,'A retry cannot silently change an already saved phone');
  const duplicate=await call('post','/api/phone-purchases',{body:{...body,imei:'123456789',client_request_id:'test-save-reference-0002'}});
  assert.equal(duplicate.statusCode,409);
  assert.equal(duplicate.body.code,'DUPLICATE_IMEI');
  assert.equal(duplicate.body.matches[0].invoice_id,sourceInvoice.id);
  assert.equal((await db.query('select count(*)::int as n from phone_purchases')).rows[0].n,1);
  const approved=await call('post','/api/phone-purchases',{body:{...body,client_request_id:'test-save-reference-0002',allow_duplicate_imei:true}});
  assert.equal(approved.statusCode,200,'Acknowledged duplicates can be recorded');
  const secondId=approved.body.purchase.id;
  const holdingBlocked=await call('post','/api/phone-holding',{body:{...body,client_request_id:'test-holding-reference-0001'}});
  assert.equal(holdingBlocked.statusCode,409);
  const holding=await call('post','/api/phone-holding',{body:{...body,imei:'SERIAL-HOLD',client_request_id:'test-holding-reference-0002'}});
  assert.equal(holding.statusCode,200);
  assert.equal((await call('post','/api/phone-holding',{body:{...body,imei:'SERIAL-HOLD',client_request_id:'test-holding-reference-0002'}})).body.item.id,holding.body.item.id);
  assert.equal((await call('post','/api/phone-purchases',{body:{...body,imei:'serial hold',client_request_id:'test-save-reference-0003'}})).statusCode,409);
  const blank=await call('post','/api/phone-purchases',{body:{...body,imei:'',client_request_id:'test-save-reference-0004',quantity:2,cost_each:700.25}});
  assert.equal(blank.statusCode,200,'Mike may omit IMEI');
  assert.equal((await call('post','/api/phone-purchases',{body:{...body,quantity:1.5}})).statusCode,400);
  const blankId=blank.body.purchase.id;
  const failedMove=await call('post','/api/phone-purchases/bulk-move',{body:{source_invoice_id:sourceInvoice.id,purchase_ids:[purchaseId,999999],invoice_id:target.id}});
  assert.equal(failedMove.statusCode,409);
  assert.equal((await db.query('select invoice_id from phone_purchases where id=$1',[purchaseId])).rows[0].invoice_id,sourceInvoice.id);
  const moved=await call('post','/api/phone-purchases/bulk-move',{body:{source_invoice_id:sourceInvoice.id,purchase_ids:[purchaseId,blankId],invoice_id:target.id}});
  assert.equal(moved.body.moved,2);
  const movedRows=(await db.query('select * from phone_purchases where invoice_id=$1 order by id',[target.id])).rows;
  assert.equal(movedRows[0].invoice_item_start,1);
  assert.equal(movedRows[1].invoice_item_start,2);
  const held=await call('post','/api/phone-purchases/bulk-move',{body:{source_invoice_id:sourceInvoice.id,purchase_ids:[secondId],destination:'Holding',holding_type:'Holding For Sale'}});
  assert.equal(held.body.moved,1);
  assert.ok((await db.query('select invoice_removed_at from phone_purchases where id=$1',[secondId])).rows[0].invoice_removed_at);
  assert.equal((await call('post','/api/phone-purchases/bulk-move',{body:{source_invoice_id:sourceInvoice.id,purchase_ids:[secondId],destination:'Holding'}})).statusCode,409,'Cannot move a removed phone twice');

  const partial=await call('patch','/api/phone-invoices/:id/final-prices',{id:target.id,body:{prices:[{id:purchaseId,final_sell_each:860},{id:blankId,final_sell_each:''}]}});
  assert.equal(partial.body.complete,false);
  assert.equal((await db.query('select sale_price from phone_invoices where id=$1',[target.id])).rows[0].sale_price,null);
  assert.equal((await call('patch','/api/phone-invoices/:id/workflow',{id:target.id,body:{payment_status:'Paid'}})).statusCode,400,'Cannot mark an unknown amount paid');
  const complete=await call('patch','/api/phone-invoices/:id/final-prices',{id:target.id,body:{prices:[{id:purchaseId,final_sell_each:860},{id:blankId,final_sell_each:760.25}]}});
  assert.equal(complete.body.total,2380.5,'Final total uses quantity and exact cents');
  let current=(await db.query('select * from phone_invoices where id=$1',[target.id])).rows[0];
  assert.equal(Number(current.sale_price),2380.5);
  assert.equal(current.status,'Pending','Prices do not ship an invoice');
  const paid=await call('patch','/api/phone-invoices/:id/workflow',{id:target.id,body:{payment_status:'Paid',payment_notes:'Transfer received'}});
  assert.equal(paid.body.invoice.status,'Pending','Payment does not ship an invoice');
  assert.ok(paid.body.invoice.paid_at);
  assert.equal((await call('patch','/api/phone-invoices/:id/final-prices',{id:target.id,body:{prices:[{id:purchaseId,final_sell_each:900}]}})).statusCode,409,'Stale phone list is rejected');
  assert.equal((await call('patch','/api/phone-invoices/:id/final-prices',{id:target.id,body:{prices:[{id:purchaseId,final_sell_each:-1},{id:blankId,final_sell_each:0}]}})).statusCode,400);
  assert.equal((await db.query('select sale_price from phone_invoices where id=$1',[target.id])).rows[0].sale_price,'2380.50','Failed prices preserve the total');
  const shipped=await call('patch','/api/phone-invoices/:id/status',{id:target.id,body:{status:'Shipped'}});
  assert.equal(shipped.body.invoice.delivery_status,'Shipped','Existing Mark Shipped button updates tracking status');
  const delivered=await call('patch','/api/phone-invoices/:id/workflow',{id:target.id,body:{delivery_status:'Delivered',tracking_number:'1Z-TEST'}});
  assert.equal(delivered.body.invoice.status,'Shipped');
  assert.ok(delivered.body.invoice.delivered_at);
  assert.equal(delivered.body.invoice.payment_status,'Paid');
  const reopened=await call('patch','/api/phone-invoices/:id/status',{id:target.id,body:{status:'Pending'}});
  assert.equal(reopened.body.invoice.delivery_status,'Not Shipped');
  assert.equal(reopened.body.invoice.delivered_at,null);
  const history=await call('get','/api/phone-invoices/:id/activity',{id:target.id});
  assert.ok(history.body.events.some(event=>event.action==='Phone moved'));
  assert.ok(history.body.events.some(event=>event.details.changes.final_sell_each));
  assert.ok(history.body.events.some(event=>event.details.changes.payment_status));
  const sourceHistory=await call('get','/api/phone-invoices/:id/activity',{id:sourceInvoice.id});
  assert.ok(sourceHistory.body.events.some(event=>event.action==='Phone moved'));
  assert.ok(sourceHistory.body.events.some(event=>event.action==='Phone removed'));
  assert.ok(sourceHistory.body.events.some(event=>event.action==='Phone added'));
  assert.equal(JSON.stringify(history.body.events).includes('photo_data_url'),false);
  await db.query('update phone_invoices set archived_at=now() where id=$1',[target.id]);
  assert.equal((await call('patch','/api/phone-invoices/:id/workflow',{id:target.id,body:{payment_status:'Awaiting Payment'}})).statusCode,404);
  const checks=await call('post','/api/phone-imei-check',{body:{imeis:['123 456 789','serial-hold','']}});
  assert.equal(checks.body.matches.length,2);
  assert.ok(checks.body.matches[0].records.some(record=>record.location==='Archived'));
  await db.exec(phoneWorkflowSchema);
  current=(await db.query('select * from phone_invoices where id=$1',[target.id])).rows[0];
  assert.equal(current.delivery_status,'Not Shipped','Reopening is preserved after redeploy');
  assert.equal(current.payment_status,'Paid','Existing payment state is preserved');
  assert.equal((await call('get','/api/phone-dashboard-settings')).body.start_date,'2026-10-10','Chosen reporting date survives deployment');
});
