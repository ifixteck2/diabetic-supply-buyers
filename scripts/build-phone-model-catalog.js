import fs from 'node:fs';
const reference=JSON.parse(fs.readFileSync(new URL('./phone-model-reference.json',import.meta.url),'utf8'));
const prices=JSON.parse(fs.readFileSync(new URL('../public/kt-prices.json',import.meta.url),'utf8'));
const models=new Map();
function clean(name) {
  return String(name || '').trim().replace(/\s+/g,' ').replace(/^iphone/i,'iPhone')
    .replace(/\b(\d+)E\b/gi,'$1e').replace(/\bmini\b/gi,'Mini').replace(/\bair\b/gi,'Air')
    .replace(/\bXr\b/gi,'XR').replace(/\bXs\b/gi,'XS')
    .replace(/^(?:iPhone\s+)?SE\s*\(2020\)$/i,'iPhone SE (2nd Gen)')
    .replace(/^(?:iPhone\s+)?SE\s*\(2022\)$/i,'iPhone SE (3rd Gen)')
    .replace(/SE\s+(2nd|3rd)(?:\s+Gen)?$/i,'SE ($1 Gen)')
    .replace(/^Google\s+(Pixel)/i,'$1').replace(/\bXl\b/gi,'XL')
    .replace(/^(?:Samsung\s+)?(?:Galaxy\s+)?(Z\s+(?:Flip|Fold)\s*\d.*)$/i,'Galaxy $1')
    .replace(/\s*\(\s*FE Model[^)]*\)\s*$/i,'');
}
function add(model,storages,replace=false) {
  model=clean(model);
  const brand=/pixel|google/i.test(model)?'Google':/galaxy|samsung|^s\d|^note/i.test(model)?'Samsung':'Apple';
  const old=models.get(model);
  const valid=storages.map(s=>String(s).replace(/\s/g,'').toUpperCase()).filter(s=>/^\d+(GB|TB)$/.test(s));
  models.set(model,{model,brand,storages:[...new Set([...(replace?[]:old?.storages || []),...valid])]});
}
for(const row of prices.rows.filter(row=>row.device_type==='Phone')) add(row.base_model || row.model,[row.storage]);
// Drive's explicit storage rows override the older bundled pricing snapshot.
for(const row of reference.models) add(row.model,row.storages,true);
const catalog=[...models.values()].sort((a,b)=>a.model.localeCompare(b.model));
const output=`// Generated by scripts/build-phone-model-catalog.js. Model names/storage only; no quoted prices.\nconst PHONE_MODEL_CATALOG = ${JSON.stringify(catalog,null,2)};\n`;
fs.writeFileSync(new URL('../public/phone-model-catalog.js',import.meta.url),output);
console.log(`Built ${catalog.length} phone models, including ${reference.models.length} checked against Drive.`);
